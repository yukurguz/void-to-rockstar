// Renders a few pixelfx effects and writes them as compact frame data for the
// trainer (sprites_data.js). jsui cannot run the pixelfx library itself, so the
// animations are baked: every frame becomes a list of horizontal colour runs.
//
// Usage: node export_sprites.mjs <path to a pixelfx checkout> [--sheet preview.png]

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const pixelfx = process.argv[2];
if (!pixelfx) {
    console.error("usage: node export_sprites.mjs <pixelfx checkout> [--sheet file.png]");
    process.exit(1);
}
const sheetArg = process.argv.indexOf("--sheet");
const fxlib = await import(pathToFileURL(join(pixelfx, "tools", "lib", "fxlib.mjs")).href);

// light: 0 drops the additive glow, which would turn into hundreds of
// in-between colours once it is flattened onto opaque pixels.
const JOBS = [
    { name: "slime", id: "critters/slime", fps: 12 },
    { name: "frog", id: "critters/frog", fps: 12 },
    { name: "burst", id: "pickups/collect-burst", fps: 15 },
    { name: "confetti", id: "ui/confetti", fps: 12 },
    { name: "storm", id: "lightning/storm-cloud", fps: 10 },
    { name: "confused", id: "status/confused", fps: 10 },
    { name: "charmed", id: "status/charmed", fps: 10 },
    { name: "star", id: "pickups/power-star", fps: 12 },
];
const ALPHA_CUT = 110;
const MAX_COLORS = 40;

function quantizer(bits) {
    const shift = 8 - bits;
    return (r, g, b) => ((r >> shift) << (bits * 2)) | ((g >> shift) << bits) | (b >> shift);
}

function bake(job, rendered, meta) {
    const { w, h, frames } = rendered;
    // Coarsen the colour grid until the palette is small enough.
    let bits = 5, keyOf, buckets;
    for (;;) {
        keyOf = quantizer(bits);
        buckets = new Map();
        for (const frame of frames) {
            const d = frame.clear;
            for (let i = 0; i < w * h; i++) {
                if (d[i * 4 + 3] < ALPHA_CUT) continue;
                const key = keyOf(d[i * 4], d[i * 4 + 1], d[i * 4 + 2]);
                const bucket = buckets.get(key) ?? buckets.set(key, [0, 0, 0, 0]).get(key);
                bucket[0] += d[i * 4]; bucket[1] += d[i * 4 + 1]; bucket[2] += d[i * 4 + 2]; bucket[3]++;
            }
        }
        if (buckets.size <= MAX_COLORS || bits === 2) break;
        bits--;
    }
    const keys = [...buckets.keys()];
    const hex = (v) => Math.round(v).toString(16).padStart(2, "0");
    const pal = keys.map((k) => { const b = buckets.get(k); return hex(b[0] / b[3]) + hex(b[1] / b[3]) + hex(b[2] / b[3]); });
    const indexOf = new Map(keys.map((k, i) => [k, i]));

    // Bounding box of everything that is ever drawn.
    let x0 = w, y0 = h, x1 = -1, y1 = -1;
    for (const frame of frames) {
        const d = frame.clear;
        for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
            if (d[(y * w + x) * 4 + 3] < ALPHA_CUT) continue;
            if (x < x0) x0 = x; if (x > x1) x1 = x; if (y < y0) y0 = y; if (y > y1) y1 = y;
        }
    }
    const byte = (v) => { if (v > 255) throw new Error(job.name + ": value " + v + " does not fit a byte"); return v.toString(16).padStart(2, "0"); };
    const packed = frames.map((frame) => {
        const d = frame.clear;
        let out = "";
        for (let y = y0; y <= y1; y++) {
            let x = x0;
            while (x <= x1) {
                const i = (y * w + x) * 4;
                if (d[i + 3] < ALPHA_CUT) { x++; continue; }
                const c = indexOf.get(keyOf(d[i], d[i + 1], d[i + 2]));
                let run = 1;
                while (x + run <= x1) {
                    const j = (y * w + x + run) * 4;
                    if (d[j + 3] < ALPHA_CUT || indexOf.get(keyOf(d[j], d[j + 1], d[j + 2])) !== c) break;
                    run++;
                }
                out += byte(x - x0) + byte(y - y0) + byte(run) + byte(c);
                x += run;
            }
        }
        return out;
    });
    return {
        w: x1 - x0 + 1, h: y1 - y0 + 1,
        ox: meta.origin[0] - x0, oy: meta.origin[1] - y0,
        fps: job.fps, loop: !!meta.loop, pal, frames: packed,
    };
}

const sprites = {};
for (const job of JOBS) {
    const fx = await fxlib.loadEffect(job.id);
    const rendered = fxlib.renderFrames(fx, { fps: job.fps, bg: "none", options: { light: 0 } });
    sprites[job.name] = bake(job, rendered, fx.meta);
    const s = sprites[job.name];
    const runs = s.frames.reduce((n, f) => n + f.length / 8, 0);
    console.log(`${job.name}: ${s.w}x${s.h}, origin ${s.ox},${s.oy}, ${s.frames.length} frames, ${s.pal.length} colours, ${runs} runs`);
}

const source = "// Generated by export_sprites.mjs from pixelfx effects. Do not edit by hand.\n"
    + "// Animations (" + JOBS.map((j) => j.id).join(", ") + ") come from pixelfx,\n"
    + "// https://github.com/patch-gg/pixelfx, MIT License,\n"
    + "// Copyright (c) 2026 Patch, Copyright (c) 2026 Hugo Duprez.\n"
    + "// Each frame is a hex string of runs: x, y, width, colour index (one byte each).\n"
    + "var SPRITES = " + JSON.stringify(sprites) + ";\n";
writeFileSync(join(HERE, "sprites_data.js"), source);
console.log("sprites_data.js:", source.length, "bytes");

// Optional contact sheet of the baked frames, to check them by eye.
if (sheetArg > 0) {
    const names = Object.keys(sprites), pad = 4, scale = 2, perRow = 12;
    const rows = names.map((n) => Math.ceil(sprites[n].frames.length / perRow));
    const cellW = Math.max(...names.map((n) => sprites[n].w)) + pad;
    const height = names.reduce((sum, n, i) => sum + rows[i] * (sprites[n].h + pad), pad);
    const sheet = fxlib.canvas(cellW * perRow + pad, height, [26, 28, 44, 255]);
    let top = pad;
    names.forEach((n, ni) => {
        const s = sprites[n];
        s.frames.forEach((f, i) => {
            const left = pad + (i % perRow) * cellW, y = top + Math.floor(i / perRow) * (s.h + pad);
            for (let k = 0; k < f.length; k += 8) {
                const v = [0, 2, 4, 6].map((o) => parseInt(f.substr(k + o, 2), 16));
                const c = s.pal[v[3]];
                sheet.rect(left + v[0], y + v[1], v[2], 1, [parseInt(c.substr(0, 2), 16), parseInt(c.substr(2, 2), 16), parseInt(c.substr(4, 2), 16), 255]);
            }
        });
        top += rows[ni] * (s.h + pad);
    });
    fxlib.save(process.argv[sheetArg + 1], Buffer.from(fxlib.upscale(sheet.data, sheet.w, sheet.h, scale).buffer).length ? pngOf(sheet, scale) : sheet.png());
    console.log("sheet:", process.argv[sheetArg + 1]);
}

function pngOf(sheet, scale) {
    const big = fxlib.canvas(sheet.w * scale, sheet.h * scale, [0, 0, 0, 255]);
    big.data.set(fxlib.upscale(sheet.data, sheet.w, sheet.h, scale));
    return big.png();
}
